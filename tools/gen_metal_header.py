#!/usr/bin/env python3 -I
"""Embed one or more Metal sources, concatenated, as a C string constant.

usage: gen_metal_header.py OUT.h NAME IN.metal [IN2.metal ...]
"""
import sys


def main(argv: list[str]) -> int:
    if len(argv) < 4:
        print("usage: gen_metal_header.py OUT.h NAME IN.metal [IN2.metal ...]", file=sys.stderr)
        return 2
    lines = []
    for source in argv[3:]:
        with open(source, encoding="utf-8") as handle:
            lines.extend(handle.read().splitlines())
    body = "\n".join(
        '    "' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"' for line in lines
    )
    text = (
        "/* Generated by tools/gen_metal_header.py from "
        f"{', '.join(path.split('/')[-1] for path in argv[3:])}. Do not edit; run tools/build-gpu.sh. */\n"
        f"static const char *const {argv[2]} =\n{body};\n"
    )
    with open(argv[1], "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"gen_metal_header: wrote {argv[1]} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
